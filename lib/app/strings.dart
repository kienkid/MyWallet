  String txTitle(TxView v) {
    final t = v.tx;
    switch (t.type) {
      case TxType.income:
      case TxType.expense:
        final c = v.category;
        if (c == null) return this[t.type.name];
        final own = categoryName(c);
        return v.parentName == null ? own : '${keyedName(v.parentName!, v.parentNameKey)} › $own';
      case TxType.transfer:
        return this['transfer'];
      case TxType.lend:
      case TxType.borrow:
      case TxType.collect:
      case TxType.repay:
        return '${this[t.type.name]} · ${v.personName ?? ''}';
    }
